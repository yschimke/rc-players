/**
 * [RcTargetProfile.of] gives, for each API level and profile combination, exactly the operations
 * AndroidX's `Operations.getOperations` does.
 *
 * The expected sets are AndroidX's own: `remote-core`'s `OperationsProfilesTest` at androidx-main
 * `21a1a95e41d` (2026-11-10, added in `353f021ee` ahead of the `48e08566f` refactor that stores a
 * profile as an opcode array) spells out the operations of API level 6 and of every profile
 * combination at level 7. They are carried here by AndroidX's constant names, in its order: level 6
 * and the level 7 baseline in full, and each combination as what it adds to that baseline.
 *
 * Before this test the tables were a transcription of 1.0.0-alpha19, and two later changes had
 * passed them by, both already in 1.0.0-alpha23: `MODIFIER_ALIGN_BY` left the experimental sets for
 * the AndroidX and Widgets profiles' own, and the experimental sets gained the 2D mesh operations
 * (and, for AndroidX, `EVENT_ACTION`). `validateFor` then reported an `alignBy` row as unplayable
 * on players that read it.
 */
class RcAndroidxProfileTablesTest {

  @Test
  fun apiLevelSixIsAndroidXsSet() {
    assertOperations(LEVEL_6, RcTargetProfile.of(6, RcProfiles.BASELINE))
    assertOperations(LEVEL_6, RcTargetProfiles.WIDGETS_V6)
  }

  @Test
  fun aLevelSevenProfileWithNoOperationsOfItsOwnGetsTheBaseline() {
    val without =
      listOf(
        RcProfiles.BASELINE,
        RcProfiles.EXPERIMENTAL,
        RcProfiles.DEPRECATED,
        RcProfiles.EXPERIMENTAL or RcProfiles.DEPRECATED,
        RcProfiles.OEM,
        RcProfiles.LOW_POWER,
        RcProfiles.ANDROID_NATIVE,
      )
    for (profiles in without) assertOperations(LEVEL_7_BASELINE, RcTargetProfile.of(7, profiles))
  }

  @Test
  fun everyLevelSevenProfileCombinationIsAndroidXsSet() {
    for ((profiles, added) in LEVEL_7_PROFILES) {
      assertOperations("$LEVEL_7_BASELINE $added", RcTargetProfile.of(7, profiles))
    }
  }

  private fun assertOperations(expected: String, actual: RcTargetProfile) {
    val names = expected.split(Regex("\\s+")).filter { it.isNotEmpty() }
    assertEquals(names.size, names.toSet().size, "a repeated constant in the expectation")
    val byOpcode = RcOperationInventory.entries.associate { it.opcode to it.constantName }
    assertEquals(
      names.sorted(),
      actual.supportedOpcodes.map { byOpcode[it] ?: "opcode $it" }.sorted(),
      actual.toString(),
    )
  }

