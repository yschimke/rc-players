package ee.schimke.composeai.rccodegen

import androidx.compose.remote.generator.OperationSchema
import androidx.compose.remote.generator.RemoteCodegenTarget
import java.nio.file.Files
import java.nio.file.Path

/**
 * rc-players' Swift wire constants: every opcode, operator and enumerated field value `RcCreation`
 * writes, as complete namespaces, from the AndroidX schema.
 *
 * Opcodes are the union of the schema and `rc-operations.manifest` (the repository's inventory,
 * which also carries constants the schema has no entry for: the 3D range, the reserved extension
 * range and the unavailable readers), named after their AndroidX `Operations` constant as the
 * manifest spells it. Everything else comes from the schema alone.
 */
class SwiftWireConstantsTarget(private val manifest: Path?) : RemoteCodegenTarget {
  override val id: String = "rc-swift-wire-constants"

  override fun generate(schema: OperationSchema): Map<String, String> =
    mapOf(OUTPUT to SwiftConstantsWriter(schema, manifestOpcodes()).write())

  private fun manifestOpcodes(): Map<Int, String> {
    val path = manifest ?: return emptyMap()
    return Files.readAllLines(path)
      .filter { it.isNotBlank() && !it.startsWith("#") }
      .associate { line ->
        val fields = line.split("|")
        fields[0].trim().toInt() to fields[1].trim()
      }
  }

  companion object {
    /** Where the file lands, relative to the repository root. */
    const val OUTPUT: String = "Sources/RcCreation/RemoteWireConstants.swift"
  }
}

private class SwiftConstantsWriter(
  private val schema: OperationSchema,
  private val manifest: Map<Int, String>,
) {
  private val out = StringBuilder()

  fun write(): String {
    out.append(
      """
      |// Generated by rc-codegen (`:rc-codegen`, target `rc-swift-wire-constants`) from AndroidX's
      |// `operations.json` (third_party/remote-generator) and rc-operations.manifest. DO NOT EDIT:
      |// run `./gradlew :rc-codegen:generateSwiftSources` and commit the result.
      |//
      |// Every namespace lists every value its source defines, used here or not, as AGENTS.md asks
      |// of native wire constants.
      |"""
        .trimMargin(),
    )
    opcodes()
    idEncoding()
    operators()
    namespace(
      "RemoteNamedVariableType",
      "`NamedVariable`'s `varType`.",
      fieldEnum("NamedVariable", "varType"),
    )
    namespace(
      "RemoteHostActionValueType",
      "`HostNamedAction`'s value `type`.",
      fieldEnum("HostNamedAction", "type").mapKeys { it.key.removeSuffix("_TYPE") },
    )
    namespace(
      "RemoteDimensionType",
      "Width and height modifier `type` (`DimensionModifierOperation.Type`).",
      fieldEnum("WidthModifierOperation", "type"),
    )
    namespace(
      "RemoteHeaderKey",
      "Modern header property tags (`Header.DOC_*` and the feature tags).",
      checkNotNull(schema.operationsByName.getValue("Header").extensions) {
          "the schema's Header has no property tags"
        }
        .supportedTags
        .associate { it.name to it.tag },
    )
    namespace(
      "RemotePaintTag",
      "`PaintBundle` tags.",
      schema.paintCommands.values.associate { it.name to it.id },
      camel = { lowerCamelFromPascal(it) },
    )
    namespace("RemotePaintStyle", "`PaintBundle`'s `Style` values.", paintEnum("Style"))
    namespace("RemoteStrokeCap", "`PaintBundle`'s `StrokeCap` values.", paintEnum("StrokeCap"))
    namespace(
      "RemoteTextFromFloatFlag",
      "`TextFromFloat`'s formatting flags.",
      fieldEnum("TextFromFloat", "flags"),
    )
    namespace(
      "RemoteModifierShape",
      "Background and border modifier `shapeType`.",
      fieldEnum("BackgroundModifierOperation", "shapeType"),
    )
    namespace(
      "RemotePositioning",
      "AndroidX `LayoutManager` positioning values, across the row and column axes.",
      fieldEnum("RowLayout", "horizontalPositioning") +
        fieldEnum("ColumnLayout", "verticalPositioning"),
    )
    namespace(
      "RemoteTextLayoutAlign",
      "`TextLayout`'s alignment values (the low half of its `textAlign` word).",
      bitEnum("TextLayout", "textAlign", "alignment"),
    )
    namespace(
      "RemoteTextLayoutOverflow",
      "`TextLayout`'s `overflow` values.",
      fieldEnum("TextLayout", "overflow").mapKeys { it.key.removePrefix("OVERFLOW_") },
    )
    namespace(
      "RemoteTextLayoutFlag",
      "`TextLayout`'s flag bits in its `textAlign` word.",
      bitFlags("TextLayout", "textAlign"),
    )
    return out.toString()
  }

  private fun opcodes() {
    val names = schema.operations.associate { it.id to it.resolvedOpCodeName } + manifest
    namespace(
      "RemoteOpcode",
      "Every `.rc` operation code, named after its AndroidX `Operations` constant.",
      names.entries.sortedBy { it.key }.associate { it.value to it.key },
    )
  }

  private fun idEncoding() {
    val encoding = checkNotNull(schema.idEncoding) { "the schema has no idEncoding" }
    line()
    line("/// How an id is NaN-boxed into a float word (`Utils.asNan`), and the first id a writer")
    line("/// gives out (`RemoteComposeState.START_ID`): ids below it are system variables.")
    line("enum RemoteIDEncoding {")
    line("  static let nanPrefix: UInt32 = ${hex(encoding.nanPrefix)}")
    line("  static let payloadMask: UInt32 = ${hex(encoding.payloadMask)}")
    line("  static let firstDataID = ${encoding.startId}")
    line("}")
  }

  private fun operators() {
    val table = checkNotNull(schema.rpnOperators) { "the schema has no float operators" }
    namespace(
      "RemoteFloatOperatorCode",
      "`AnimatedFloatExpression`'s operators, as offsets from `offset`.",
      mapOf("OFFSET" to table.offset) + table.operators.associate { it.name to it.id },
    )
  }

  private fun fieldEnum(operation: String, field: String): Map<String, Int> =
    checkNotNull(
      schema.operationsByName.getValue(operation).fields.first { it.name == field }.enumValues,
    ) {
      "$operation.$field has no enum in the schema"
    }

  private fun bitEnum(operation: String, field: String, bits: String): Map<String, Int> =
    checkNotNull(
      schema.operationsByName
        .getValue(operation)
        .fields
        .first { it.name == field }
        .bits
        ?.first { it.name == bits }
        ?.enumValues,
    ) {
      "$operation.$field.$bits has no enum in the schema"
    }

  /** The single-bit fields of [operation]'s [field], as masks. */
  private fun bitFlags(operation: String, field: String): Map<String, Int> =
    schema.operationsByName
      .getValue(operation)
      .fields
      .first { it.name == field }
      .bits
      .orEmpty()
      .filter { !it.range.contains("..") }
      .associate { it.name to (1 shl it.range.toInt()) }

  private fun paintEnum(command: String): Map<String, Int> =
    checkNotNull(
      schema.paintCommands.values.first { it.name == command }.fields.firstOrNull()?.enumValues,
    ) {
      "paint command $command has no enum in the schema"
    }

  private fun namespace(
    name: String,
    doc: String,
    values: Map<String, Int>,
    camel: (String) -> String = ::lowerCamel,
  ) {
    check(values.isNotEmpty()) { "$name would be empty" }
    line()
    line("/// $doc")
    line("enum $name {")
    val seen = mutableSetOf<String>()
    // By value, then name: deterministic whatever order the schema's maps iterate in.
    for ((key, value) in values.entries.sortedWith(compareBy({ it.value }, { it.key }))) {
      val swiftName = swiftIdentifier(camel(key))
      check(seen.add(swiftName)) { "$name has two values named $swiftName" }
      line("  static let $swiftName = ${swiftDecimal(value)}")
    }
    line("}")
  }

  private fun line(text: String = "") {
    out.append(text).append('\n')
  }
}

/** `FILL_PARENT_MAX_WIDTH` → `fillParentMaxWidth`, `camelCase` stays as it is. */
internal fun lowerCamel(name: String): String {
  if (!name.contains('_') && name.any { it.isLowerCase() }) return lowerCamelFromPascal(name)
  val parts = name.lowercase().split('_').filter { it.isNotEmpty() }
  return parts.first() + parts.drop(1).joinToString("") { it.replaceFirstChar(Char::uppercase) }
}

/** `StrokeWidth` → `strokeWidth`, `ColorId` → `colorId`. */
internal fun lowerCamelFromPascal(name: String): String = name.replaceFirstChar(Char::lowercase)

private val swiftKeywords =
  setOf("default", "case", "class", "struct", "enum", "func", "let", "var", "in", "is", "as", "if")

private fun swiftIdentifier(name: String): String =
  when {
    name in swiftKeywords -> "`$name`"
    name.first().isDigit() -> "_$name"
    else -> name
  }

/** `0xFF80_0000`: grouped by four, as swift-format's `GroupNumericLiterals` asks. */
private fun hex(value: Int): String =
  "0x" + Integer.toHexString(value).uppercase().padStart(8, '0').chunked(4).joinToString("_")

/**
 * `3_211_264`: grouped by three from five digits up, as swift-format's `GroupNumericLiterals` asks.
 */
private fun swiftDecimal(value: Int): String {
  val digits = kotlin.math.abs(value.toLong()).toString()
  val grouped =
    if (digits.length < 5) digits else digits.reversed().chunked(3).joinToString("_").reversed()
  return if (value < 0) "-$grouped" else grouped
}

/** rc-players' own targets. */
fun rcPlayersTargets(manifest: Path?): List<RemoteCodegenTarget> =
  listOf(SwiftWireConstantsTarget(manifest))
